// Equal Earth projection (Savric et al. 2018), same maths as the map image.
// lat/lon in degrees -> pixel (x, y) inside the QW_MAP_W x QW_MAP_H bitmap.
inline void qwMapProject(float latDeg, float lonDeg, int &px, int &py) {
  const float A1 = 1.340264f, A2 = -0.081106f, A3 = 0.000893f, A4 = 0.003796f;
  const float KX = 36.94631f, KY = 36.81600f;      // pixels per projection unit
  const float CX = 100.0f, CY = 48.5f;      // pixel of lat 0 / lon 11E
  float d = lonDeg - 11.0f;
  while (d < -180.0f) d += 360.0f;
  while (d > 180.0f) d -= 360.0f;
  float phi = latDeg * 0.017453293f, lam = d * 0.017453293f;
  float th = asinf(0.8660254f * sinf(phi));
  float t2 = th * th, t6 = t2 * t2 * t2;
  float x = 2.0f * 1.7320508f * lam * cosf(th) /
            (3.0f * (9.0f * A4 * t6 * t2 + 7.0f * A3 * t6 + 3.0f * A2 * t2 + A1));
  float y = th * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  px = (int)lroundf(CX + KX * x);
  py = (int)lroundf(CY - KY * y);
}
