inline bool moonTexInk(int16_t tx, int16_t ty) {
  if (tx < 0 || ty < 0 || tx >= MOON_TEX_SIZE || ty >= MOON_TEX_SIZE)
    return false;
  return (MOON_TEXTURE[ty][tx >> 3] & (0x80 >> (tx & 7))) != 0;
}

// Is the pixel at (ox, oy), relative to the moon's center, on the
// lit side? Same terminator formula as the base disc.
inline bool moonPixelLit(int16_t ox, int16_t oy, int16_t radius,
                         const MoonData &moon) {
  double w = sqrt(max(0.0, (double)radius * radius - (double)oy * oy));
  double k = moon.illumination;
  double t = moon.waxing ? (1.0 - 2.0 * k) * w : (2.0 * k - 1.0) * w;
  return moon.waxing ? (ox >= t) : (ox <= t);
}

// Draws the texture's dark pixels on the lit part of the disc. The
// texture is scaled to any radius by nearest-neighbour sampling.
inline void drawMoonTexture(Adafruit_GFX &display, int16_t cx, int16_t cy,
                            int16_t radius, const MoonData &moon) {
  for (int16_t oy = -radius + 1; oy <= radius - 1; oy++) {
    for (int16_t ox = -radius + 1; ox <= radius - 1; ox++) {
      if ((int32_t)ox * ox + (int32_t)oy * oy >=
          (int32_t)(radius - 1) * (radius - 1))
        continue;
      if (!moonPixelLit(ox, oy, radius, moon)) continue;
      int16_t tx = (int16_t)lroundf((float)ox * MOON_TEX_HALF / radius) +
                   MOON_TEX_HALF;
      int16_t ty = (int16_t)lroundf((float)oy * MOON_TEX_HALF / radius) +
                   MOON_TEX_HALF;
      if (moonTexInk(tx, ty)) display.drawPixel(cx + ox, cy + oy, qwInk());
    }
  }
}

// Draws the lit part (white) and the dark part (black), centered
// at (cx, cy), no bitmap. The terminator is an ellipse whose width
// at each row follows the illuminated fraction exactly.
inline void drawMoonIcon(Adafruit_GFX &display, int16_t cx, int16_t cy,
                          int16_t diameter, const MoonData &moon) {
  int16_t radius = diameter / 2;
  if (radius < 2) return;
  double k = moon.illumination;

  for (int16_t dy = -radius; dy <= radius; dy++) {
    double w = sqrt(max(0.0, (double)radius * radius - (double)dy * dy));
    int16_t rowWidth = (int16_t)round(w);
    if (rowWidth <= 0) continue;

    // Terminator position on this row.
    double t = moon.waxing ? (1.0 - 2.0 * k) * w : (2.0 * k - 1.0) * w;

    for (int16_t dx = -rowWidth; dx <= rowWidth; dx++) {
      bool lit = moon.waxing ? (dx >= t) : (dx <= t);
      display.drawPixel(cx + dx, cy + dy, lit ? qwPaper() : qwInk());
    }
  }
  drawMoonTexture(display, cx, cy, radius, moon);
  display.drawCircle(cx, cy, radius, qwInk());
}