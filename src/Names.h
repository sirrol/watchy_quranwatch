#pragma once
/*
  Names.h
  ------------------------------------------------------------
  NAMES OF ALLAH - quiz and learning mode for QuranWatch (included by
  Games.h). 107 names, taken from asmaalhusna.com (the list is marked
  "non-exhaustive" there): Arabic (Scheherazade New), transliteration,
  short English title and a short explanation.

    QUIZ  : 10 questions, 4 answers each, two kinds mixed at random:
            - you see the Arabic name + its transliteration, you pick
              the right meaning among 4;
            - you see a meaning, you pick the right Arabic name among 4.
            UP/DOWN move the highlight, MENU confirms.
            After each answer: the name in Arabic, its transliteration,
            its title (page 1) and its explanation (page 2).
    LEARN : browse the 107 names (UP/DOWN, hold = faster), MENU switches
            between the name and its explanation.

  Progress is kept in flash: a name counts as MASTERED after 3 right
  answers in a row (a wrong answer resets it). Names you know less are
  asked more often. Names whose meanings are close (the generous ones,
  the forgiving ones, ...) are never offered together as answers.

  Data: ArabicNames.h (bitmaps) and AsmaData.h (texts) are generated by
  nq/genar.py. Plain ASCII only on screen except the Arabic bitmaps.
*/

