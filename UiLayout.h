// ---------------------------------------------------------------
// Verse number between ornate brackets (like the mushaf's verse-end
// marks). Neither the brackets nor Eastern Arabic digits exist in the
// built-in font, so both are drawn pixel by pixel.
// ---------------------------------------------------------------
//
// Eastern Arabic digits ٠ ١ ٢ ٣ ٤ ٥ ٦ ٧ ٨ ٩, bold, 10 px tall, same
// baseline for all (so ٠ sits at mid height, like a real zero dot).
// One uint16_t per row; bit (9 - column) is set for an ink pixel.
constexpr uint8_t BIG_DIGIT_ROWS = 10;
static const uint8_t BIG_DIGIT_W[10] = {3, 5, 9, 9, 7, 8, 8, 9, 9, 9};
static const uint16_t BIG_DIGITS[10][BIG_DIGIT_ROWS] = {
    {0x000, 0x000, 0x000, 0x000, 0x380, 0x380, 0x380, 0x000, 0x000, 0x000}, // 0 w=3
    {0x380, 0x380, 0x180, 0x1C0, 0x1C0, 0x1C0, 0x1C0, 0x1C0, 0x1C0, 0x0C0}, // 1 w=5
    {0x38E, 0x38E, 0x1FC, 0x1F8, 0x1C0, 0x1C0, 0x0C0, 0x0C0, 0x0C0, 0x0C0}, // 2 w=9
    {0x3B6, 0x3B6, 0x1FE, 0x1FC, 0x1C0, 0x1C0, 0x0C0, 0x0C0, 0x0C0, 0x0C0}, // 3 w=9
    {0x070, 0x1F0, 0x1C0, 0x1C0, 0x1E0, 0x1E0, 0x380, 0x380, 0x3F8, 0x1F0}, // 4 w=7
    {0x0E0, 0x1F0, 0x1B0, 0x3B8, 0x3B8, 0x3B8, 0x3B8, 0x3B8, 0x3F8, 0x1F0}, // 5 w=8
    {0x3F8, 0x3F8, 0x0B8, 0x038, 0x038, 0x018, 0x018, 0x01C, 0x01C, 0x01C}, // 6 w=8
    {0x38C, 0x19C, 0x1DC, 0x1D8, 0x0F8, 0x0F8, 0x0F0, 0x070, 0x070, 0x070}, // 7 w=9
    {0x070, 0x070, 0x070, 0x0F0, 0x0F8, 0x0F8, 0x1D8, 0x1DC, 0x19C, 0x38C}, // 8 w=9
    {0x1F0, 0x3F8, 0x3B8, 0x3B8, 0x1F8, 0x07C, 0x01C, 0x01C, 0x01C, 0x00C}, // 9 w=9
};

// Total width of `value` written in these digits (1 px between them).
inline int16_t arabicNumberWidth(int value) {
  char digits[6];
  snprintf(digits, sizeof(digits), "%d", value);
  int n = (int)strlen(digits);
  int16_t w = 0;
  for (int i = 0; i < n; i++) w += BIG_DIGIT_W[digits[i] - '0'] + (i ? 1 : 0);
  return w;
}

// Draws `value` (no leading zeros), top-left corner at (x, y). Digits
// read left to right, like in a mushaf (286 -> ٢٨٦).
inline void drawArabicNumber(Adafruit_GFX &d, int value, int16_t x,
                             int16_t y) {
  char digits[6];
  snprintf(digits, sizeof(digits), "%d", value);
  for (int i = 0; digits[i]; i++) {
    int g = digits[i] - '0';
    for (int row = 0; row < BIG_DIGIT_ROWS; row++) {
      for (int col = 0; col < BIG_DIGIT_W[g]; col++) {
        if (BIG_DIGITS[g][row] & (1 << (9 - col))) {
          d.drawPixel(x + col, y + row, qwInk());
        }
      }
    }
    x += BIG_DIGIT_W[g] + 1;
  }
}

// Ornate bracket, a 1-bit reduction of the verse-end marker U+FD3F
// (a tapered crescent blade with a flared cross-flower and a hole in
// the middle), 12 px wide and 25 px tall. The table is the CLOSING
// bracket; the opening one is the same bitmap mirrored left-right.
// Bit (W - 1 - column) of a row is set for an ink pixel.
constexpr int16_t ORNATE_BRACKET_W = 12;
constexpr int16_t ORNATE_BRACKET_H = 25;
static const uint16_t ORNATE_BRACKET[ORNATE_BRACKET_H] = {
    0x0400, 0x0600, 0x0300, 0x0380, 0x0180, 0x01C0,
    0x00C0, 0x00E0, 0x01F8, 0x00F8, 0x03F6, 0x079E,
    0x0F9F, 0x079F, 0x07FE, 0x00F0, 0x01F8, 0x00E0,
    0x00C0, 0x00C0, 0x0180, 0x0380, 0x0300, 0x0600,
    0x0C00,
};

// `x` = left edge of the bracket, `cy` = vertical center.
// left = true : opening bracket (mirrored), false : closing bracket.
inline void drawOrnateBracket(Adafruit_GFX &d, int16_t x, int16_t cy,
                              bool left) {
  for (int row = 0; row < ORNATE_BRACKET_H; row++) {
    for (int col = 0; col < ORNATE_BRACKET_W; col++) {
      if (ORNATE_BRACKET[row] & (1 << (ORNATE_BRACKET_W - 1 - col))) {
        int16_t px = left ? x + (ORNATE_BRACKET_W - 1 - col) : x + col;
        d.drawPixel(px, cy - ORNATE_BRACKET_H / 2 + row, qwInk());
      }
    }
  }
}

// Verse number between the two brackets, centered on (cx, cy).
inline void drawVerseWithBrackets(Adafruit_GFX &d, int value, int16_t cx,
                                  int16_t cy) {
  const int16_t bracketW = ORNATE_BRACKET_W, gap = 2;
  int16_t numW = arabicNumberWidth(value);
  int16_t totalW = bracketW + gap + numW + gap + bracketW;
  int16_t x0 = cx - totalW / 2;
  drawOrnateBracket(d, x0, cy, true);
  drawArabicNumber(d, value, x0 + bracketW + gap, cy - BIG_DIGIT_ROWS / 2);
  drawOrnateBracket(d, x0 + bracketW + gap + numW + gap, cy, false);
}

