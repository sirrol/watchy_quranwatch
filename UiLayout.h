// ---------------------------------------------------------------
// Top-level entry point
// ---------------------------------------------------------------
// Prayer alert: "<45min", "<30min", "<15min", then "Now".
// Shown under the quarter-hour dots; it replaces the special-day
// message while it is active.
//
// - The three "<" stages follow the clock quarters, exactly like the
//   dots: at each quarter (:00 :15 :30 :45) the time left until the
//   next prayer is rounded from that quarter, so the text only changes
//   every 15 minutes.
// - "Now" appears at the prayer time itself and goes away at the next
//   quarter, unless that quarter is less than 5 minutes after the
//   prayer, in which case it waits for the quarter after.
// - Sunrise is not a prayer here. After Isha the next prayer is
//   tomorrow's Fajr.
// ---------------------------------------------------------------
enum PrayerAlertStage : uint8_t {
  ALERT_NONE = 0,
  ALERT_45,   // "<45min"
  ALERT_30,   // "<30min"
  ALERT_15,   // "<15min"
  ALERT_NOW   // "Now"
};

struct PrayerAlert {
  uint8_t stage;   // PrayerAlertStage
  uint8_t prayer;  // 0 Fajr, 1 Dhuhr, 2 Asr, 3 Maghrib, 4 Isha
};

inline void alertNextDate(int &y, int &m, int &d) {
  static const uint8_t dim[12] = {31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
  int days = dim[(m >= 1 && m <= 12) ? m - 1 : 0];
  if (m == 2 && (y % 4 == 0 && (y % 100 != 0 || y % 400 == 0))) days = 29;
  if (++d > days) {
    d = 1;
    if (++m > 12) { m = 1; y++; }
  }
}

inline PrayerAlert computePrayerAlert(const AppSettings &settings, int y,
                                      int m, int d, int nowMin) {
  PrayerAlert a = {ALERT_NONE, 0};
  PrayerTimesResult t = calculatePrayerTimes(y, m, d, settings);
  int times[5] = {t.fajrMin, t.dhuhrMin, t.asrMin, t.maghribMin, t.ishaMin};

  // "Now": from the prayer time to the first quarter >= prayer + 5 min.
  for (int i = 0; i < 5; i++) {
    int end = ((times[i] + 5 + 14) / 15) * 15;
    if (nowMin >= times[i] && nowMin < end) {
      a.stage = ALERT_NOW;
      a.prayer = (uint8_t)i;
      return a;
    }
  }

  // Next prayer (tomorrow's Fajr once Isha has passed).
  int nextAbs = -1, nextIdx = 0;
  for (int i = 0; i < 5; i++) {
    if (times[i] > nowMin) { nextAbs = times[i]; nextIdx = i; break; }
  }
  if (nextAbs < 0) {
    int ty = y, tm = m, td = d;
    alertNextDate(ty, tm, td);
    PrayerTimesResult tomorrow = calculatePrayerTimes(ty, tm, td, settings);
    nextAbs = 1440 + tomorrow.fajrMin;
    nextIdx = 0;
  }

  int quarter = (nowMin / 15) * 15;
  int left = nextAbs - quarter;  // always > 0 here
  if (left <= 15) a.stage = ALERT_15;
  else if (left <= 30) a.stage = ALERT_30;
  else if (left <= 45) a.stage = ALERT_45;
  a.prayer = (uint8_t)nextIdx;
  return a;
}

// Minaret icon with sound waves, 16 x 18, one bit per pixel
// (original artwork, bit 15 = leftmost pixel).
constexpr int16_t ALERT_ICON_W = 16, ALERT_ICON_H = 18;
static const uint16_t ALERT_ICON[ALERT_ICON_H] = {
    0x0180, 0x0180, 0x03C0, 0x03C0, 0x07E0, 0x0FF0, 0x07E0, 0x23C4, 0x4BD2, 0x524A, 0x524A, 0x2BD4, 0x0240, 0x0240, 0x0240, 0x0240, 0x07E0, 0x0FF0
};

inline void drawAlertIcon(Adafruit_GFX &d, int16_t x, int16_t y,
                          uint16_t color) {
  for (int16_t r = 0; r < ALERT_ICON_H; r++) {
    uint16_t bits = ALERT_ICON[r];
    if (!bits) continue;
    for (int16_t c = 0; c < ALERT_ICON_W; c++)
      if (bits & (1U << (15 - c))) d.drawPixel(x + c, y + r, color);
  }
}

inline void drawZoneAlert(Adafruit_GFX &d, uint8_t stage) {
  using namespace UiZones;
  static const char *nums[5] = {"", "<45", "<30", "<15", "Now"};
  if (stage < ALERT_45 || stage > ALERT_NOW) return;
  const char *num = nums[stage];
  const char *suffix = (stage == ALERT_NOW) ? "" : "min";  // smaller, baseline-aligned

  const int16_t boxTop = 138, boxH = 20, gap = 4, sufGap = 2;
  int16_t cx = (R2_COL2_X0 + R2_COL2_X1) / 2;
  int16_t numW = interTextWidth(num, true);
  int16_t sufW = suffix[0] ? sufGap + interTextWidth(suffix, false) : 0;
  int16_t total = ALERT_ICON_W + gap + numW + sufW;
  int16_t x = cx - total / 2;

  uint16_t color = qwInk();
  if (stage == ALERT_NOW) {  // inverted box for the prayer time itself
    d.fillRect(R2_COL2_X0 + 3, boxTop, (R2_COL2_X1 - R2_COL2_X0) - 5, boxH,
               qwInk());
    color = qwPaper();
  }
  drawAlertIcon(d, x, boxTop + 1, color);
  int16_t tx = x + ALERT_ICON_W + gap;
  drawInterText(d, num, tx, boxTop + 4, true, color);          // caps 12 px
  if (suffix[0])
    drawInterText(d, suffix, tx + numW + sufGap, boxTop + 8, false, color);  // caps 8 px
}

// ---------------------------------------------------------------
// Next prayer, shown under the quarter-hour dots when there is neither
// a prayer alert nor a special-day message: its name (small) with the
// time left below it (large), e.g. "MAGHRIB" / "<2h". The hours are
// rounded up and, like the dots and the alert, only change every
// quarter of an hour. Under 45 minutes the alert ("<45min" ...) takes
// over, so the sequence reads <3h, <2h, <1h, <45min, <30min, <15min,
// Now. Sunrise is not a prayer here; after Isha it is tomorrow's Fajr.
// ---------------------------------------------------------------
struct NextPrayer {
  uint8_t prayer;  // 0 Fajr, 1 Dhuhr, 2 Asr, 3 Maghrib, 4 Isha
  int leftMin;     // minutes from the last quarter hour to that prayer
};

inline NextPrayer findNextPrayer(const AppSettings &settings, int y, int m,
                                 int d, int nowMin) {
  PrayerTimesResult t = calculatePrayerTimes(y, m, d, settings);
  int times[5] = {t.fajrMin, t.dhuhrMin, t.asrMin, t.maghribMin, t.ishaMin};
  int quarter = (nowMin / 15) * 15;
  for (int i = 0; i < 5; i++) {
    if (times[i] > nowMin) return {(uint8_t)i, times[i] - quarter};
  }
  int ty = y, tm = m, td = d;
  alertNextDate(ty, tm, td);
  PrayerTimesResult tomorrow = calculatePrayerTimes(ty, tm, td, settings);
  return {0, 1440 + tomorrow.fajrMin - quarter};
}

inline void drawZoneNextPrayer(Adafruit_GFX &d, const NextPrayer &np) {
  using namespace UiZones;
  static const char *names[5] = {"FAJR", "DHUHR", "ASR", "MAGHRIB", "ISHA"};
  const char *name = names[np.prayer < 5 ? np.prayer : 0];
  int hours = (np.leftMin + 59) / 60;
  if (hours < 1) hours = 1;
  char left[16];
  snprintf(left, sizeof(left), "<%dh", hours);

  int16_t cx = (R2_COL2_X0 + R2_COL2_X1) / 2;
  drawInterCentered(d, name, cx, 136, false);  // caps 8 px: rows 136..143
  drawInterCentered(d, left, cx, 146, true);   // caps 12 px: rows 146..157
}

// ---------------------------------------------------------------
inline void drawMainFace(Adafruit_GFX &d, const AppSettings &settings,
                          const QuranBookmark &bookmark, int gYear, int gMonth,
                          int gDay, int hour24, int minute, time_t utcNow,
                          float batteryVoltage, uint8_t stars) {
  d.fillScreen(qwPaper());

  HijriDate hijri =
      gregorianToHijri(gYear, gMonth, gDay, settings.hijriAdjustment);
  PrayerTimesResult prayers = calculatePrayerTimes(gYear, gMonth, gDay, settings);
  int nowMinutes = hour24 * 60 + minute;
  PrayerIndex current = currentPrayerIndex(nowMinutes, prayers);

  drawZoneMoon(d, utcNow);
  drawZoneInfo(d, hijri, batteryVoltage);
  drawZoneBookmark(d, bookmark);
  drawZoneStars(d, stars);
  drawZoneHijriGrid(d, hijri);
  drawZoneHour(d, hour24, minute);
  HijriDate hijriTomorrow = jdnToHijri(
      gregorianToJDN(gYear, gMonth, gDay) + 1, settings.hijriAdjustment);
  PrayerAlert alert =
      computePrayerAlert(settings, gYear, gMonth, gDay, nowMinutes);
  if (alert.stage != ALERT_NONE) {
    drawZoneAlert(d, alert.stage);  // replaces the special-day message
  } else {
    SpecialDay special = findSpecialDay(hijri, hijriTomorrow, nowMinutes,
                                        prayers.maghribMin);
    if (special.kind != SPECIAL_NONE) {
      drawZoneSpecial(d, special);
    } else {
      drawZoneNextPrayer(
          d, findNextPrayer(settings, gYear, gMonth, gDay, nowMinutes));
    }
  }
  drawZoneQuranBars(d, bookmark);
  drawZonePrayerTimes(d, prayers, current);
  drawSeparators(d);
}