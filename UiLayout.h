inline int16_t interIndex(char c) {
  for (int16_t i = 0; INTER_CHARS[i]; i++)
    if (INTER_CHARS[i] == c) return i;
  return -1;
}

inline int16_t interTextWidth(const char *text, bool large) {
  const uint8_t *wt = large ? INTER_L_W : INTER_S_W;
  int16_t w = 0;
  for (const char *p = text; *p; p++) {
    int16_t i = interIndex(*p);
    if (i < 0) continue;
    if (*p == ' ') w += large ? 5 : 3;   // narrow space
    else w += wt[i] + 1;                  // glyph + 1 px gap
  }
  return w > 0 ? w - 1 : 0;
}

// (x, y) = left edge and top of the capital letters.
inline void drawInterText(Adafruit_GFX &d, const char *text, int16_t x,
                          int16_t y, bool large, uint16_t color) {
  const int16_t rows = large ? INTER_L_ROWS : INTER_S_ROWS;
  const int16_t capGap = 2;  // rows above the cap line in each glyph
  for (const char *p = text; *p; p++) {
    int16_t i = interIndex(*p);
    if (i < 0) continue;
    if (*p == ' ') { x += large ? 5 : 3; continue; }
    int16_t w = large ? INTER_L_W[i] : INTER_S_W[i];
    for (int16_t r = 0; r < rows; r++) {
      uint32_t bits = large ? INTER_L_BITS[i][r] : INTER_S_BITS[i][r];
      if (!bits) continue;
      for (int16_t c = 0; c < w; c++)
        if (bits & (1UL << (31 - c)))
          d.drawPixel(x + c, y - capGap + r, color);
    }
    x += w + 1;
  }
}

inline void drawInterCentered(Adafruit_GFX &d, const char *text, int16_t cx,
                              int16_t y, bool large) {
  drawInterText(d, text, cx - interTextWidth(text, large) / 2, y, large,
                qwInk());
}

