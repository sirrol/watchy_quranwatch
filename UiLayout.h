      bool isCurrent = isCurrentHijriMonth(monthNum, hijri);
      if (isCurrent) {
        d.fillRect(cellX0 + 2, cellY0 + 2, cellW - 4, cellH - 4, qwInk());
      }

      d.setTextColor(isCurrent ? qwPaper() : qwInk());
